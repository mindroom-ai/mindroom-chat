// @ts-check
/**
 * Third-party notices: the license and notice files of every production dependency in
 * package-lock.json (packages it marks `dev` or `devOptional` are left out), read from the installed
 * packages in node_modules, and the same for the package-lock.json of each client plugin that
 * MINDROOM_CLIENT_PLUGINS lists, where installed. The build writes them to
 * public/licenses/THIRD_PARTY_NOTICES.txt beside LICENSE and NOTICE, the dev server serves the same
 * file, and Settings > About opens it.
 *
 * The output depends only on the lockfile and the installed packages: entries are sorted by name and
 * version, and nothing in it changes from one run to the next. A license text that an earlier entry
 * already printed is named, not repeated.
 *
 * Usage: node scripts/third-party-notices.mjs [<output file>]   (default: standard output)
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SHARED_PACKAGES, readClientPlugins } from './client-plugins.mjs';

/** Where the notices live in the build output and on the dev server. */
export const THIRD_PARTY_NOTICES_FILE = 'public/licenses/THIRD_PARTY_NOTICES.txt';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
// LICENSE, LICENCE.md, LICENSE-MIT, COPYING, NOTICE.txt and the like, at the package root.
const NOTICE_FILE_NAME = /^(?:licen[cs]e|copying|notice)(?:[-._].*)?$/i;
const RULE = '='.repeat(80);

const HEADER = `Third-party notices

MindRoom Chat (mindroom-client) is licensed under the Apache License 2.0; see
LICENSE and NOTICE beside this file. NOTICE also covers the fonts, the native
project templates and the code ported from other projects.

Below are the production dependencies in package-lock.json, which include
everything the web app and the iOS and Android apps take from npm, and those of
the client plugins built in: each one's declared license, then the license and
notice files it ships.

Generated by scripts/third-party-notices.mjs.`;

/**
 * @typedef {{ license?: string, author?: string | { name?: string },
 *   repository?: string | { url?: string }, homepage?: string }} Manifest
 */

/** A browsable URL from a manifest's `repository` (`git+https://...git`, `git@host:a/b`, `github:a/b`, `a/b`). */
const sourceUrl = (/** @type {Manifest} */ manifest) => {
  const repository =
    typeof manifest.repository === 'string' ? manifest.repository : manifest.repository?.url;
  if (!repository) return manifest.homepage;
  const shorthand = /^(?:github:)?([\w.-]+\/[\w.-]+)$/.exec(repository);
  if (shorthand) return `https://github.com/${shorthand[1]}`;
  return repository
    .replace(/^git\+/, '')
    .replace(/^git@([^:/]+):/, 'https://$1/')
    .replace(/^git:\/\//, 'https://')
    .replace(/^ssh:\/\/git@/, 'https://')
    .replace(/\.git$/, '');
};

/** The text of a notice file with its line endings normalized and its trailing blank space gone. */
const readNotice = (/** @type {string} */ file) =>
  readFileSync(file, 'utf8').replace(/\r\n?/g, '\n').trimEnd();

/**
 * The notices file for the dependencies installed under `root` (the repository by default) and in
 * each client plugin directory of `pluginDirs` (by default those MINDROOM_CLIENT_PLUGINS lists).
 * @param {string} [root]
 * @param {string[]} [pluginDirs]
 */
export const thirdPartyNotices = (
  root = ROOT,
  pluginDirs = readClientPlugins(process.env.MINDROOM_CLIENT_PLUGINS).map(({ dir }) => dir)
) => {
  /** @type {Map<string, { name: string, version: string, dir: string }>} */
  const packages = new Map();
  /** Adds the production packages of `base`'s package-lock.json; a plugin's only where installed. */
  const addLocked = (/** @type {string} */ base, plugin = false) => {
    const lockFile = join(base, 'package-lock.json');
    if (plugin && !existsSync(lockFile)) {
      const modules = join(base, 'node_modules');
      // A node_modules with only dot entries, such as a tool's .cache, holds no installed packages.
      if (!existsSync(modules) || readdirSync(modules).every((name) => name.startsWith('.')))
        return;
      throw new Error(
        `MINDROOM_CLIENT_PLUGINS: ${base}: has node_modules but no package-lock.json, which the third-party notices read; install its packages with npm`
      );
    }
    const lock = JSON.parse(readFileSync(lockFile, 'utf8'));
    if (!lock.packages)
      throw new Error(`${lockFile} lists no "packages" (npm 7 or newer writes them)`);
    for (const [path, entry] of Object.entries(lock.packages)) {
      if (!path.startsWith('node_modules/') || entry.dev || entry.devOptional || entry.link)
        continue;
      const name = path.slice(path.lastIndexOf('node_modules/') + 'node_modules/'.length);
      // A plugin's lockfile also lists what its install left out, such as optional and peer
      // dependencies (npm ci --omit=optional --omit=peer), and its copies of the packages the app
      // shares, which the bundle takes from the app.
      const dir = join(base, path);
      if (plugin && (SHARED_PACKAGES.includes(name) || !existsSync(dir))) continue;
      const key = `${name}@${entry.version}`;
      if (!packages.has(key)) packages.set(key, { name, version: entry.version, dir });
    }
  };
  addLocked(root);
  pluginDirs.forEach((dir) => addLocked(dir, true));
  const sorted = [...packages.values()].sort((a, b) =>
    a.name === b.name ? compare(a.version, b.version) : compare(a.name, b.name)
  );

  /** The first package that printed each text. */
  const printed = new Map();
  const entries = sorted.map(({ name, version, dir }) => {
    /** @type {Manifest} */
    const manifest = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
    const lines = [RULE, `${name} ${version}`, `License: ${manifest.license ?? 'not declared'}`];
    const source = sourceUrl(manifest);
    if (source) lines.push(`Source: ${source}`);
    const files = readdirSync(dir, { withFileTypes: true })
      .filter((file) => file.isFile() && NOTICE_FILE_NAME.test(file.name))
      .map((file) => file.name)
      .sort(compare);
    if (files.length === 0) {
      const author = typeof manifest.author === 'string' ? manifest.author : manifest.author?.name;
      lines.push(
        '',
        'The package ships no license file; the license above is the one its package.json declares' +
          (author ? `, by ${author}.` : '.')
      );
    }
    files.forEach((file) => {
      const text = readNotice(join(dir, file));
      const first = printed.get(text);
      if (first) {
        lines.push('', `File ${file}: the same text as ${first} above.`);
        return;
      }
      printed.set(text, `${name} ${version}'s ${file}`);
      lines.push('', `File ${file}:`, '', text);
    });
    return lines.join('\n');
  });
  return `${[HEADER, ...entries].join('\n\n')}\n`;
};

/** Code-point order, the same on every machine and locale. */
function compare(/** @type {string} */ a, /** @type {string} */ b) {
  if (a === b) return 0;
  return a < b ? -1 : 1;
}

/**
 * Vite plugin: emits the notices into the build output and serves them from the dev server.
 * @returns {import('vite').Plugin}
 */
export const thirdPartyNoticesPlugin = () => ({
  name: 'mindroom-third-party-notices',
  configureServer(server) {
    server.middlewares.use(`/${THIRD_PARTY_NOTICES_FILE}`, (_request, response) => {
      response.setHeader('Content-Type', 'text/plain; charset=utf-8');
      response.end(thirdPartyNotices());
    });
  },
  generateBundle() {
    this.emitFile({
      type: 'asset',
      fileName: THIRD_PARTY_NOTICES_FILE,
      source: thirdPartyNotices(),
    });
  },
});

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const notices = thirdPartyNotices();
  const output = process.argv[2];
  if (output) writeFileSync(output, notices);
  else process.stdout.write(notices);
}
